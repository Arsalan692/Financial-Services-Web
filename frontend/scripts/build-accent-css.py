"""Generate src/styles/accent.css from the theme's stylesheets.

The theme hard-codes its accent (#48c7ec) in ~190 declarations. Rather than
editing the vendor CSS, this copies just those declarations — same selector,
same @media wrapper, same !important — with the colour swapped for
var(--fx-accent). Changing the brand colour is then one variable in theme.css.

    python scripts/build-accent-css.py
"""
import re, pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
SOURCES = ["public/assets/css/offcanvas-menu.css", "public/assets/css/style.css"]
HEX = re.compile(r"#48c7ec", re.I)
RGB = re.compile(r"rgba\(\s*72\s*,\s*199\s*,\s*236\s*,\s*([\d.]+)\s*\)")

def strip_comments(css): return re.sub(r"/\*.*?\*/", "", css, flags=re.S)

def blocks(css):
    """Yield (prelude, body) for top-level blocks, brace-aware."""
    i, n = 0, len(css)
    while i < n:
        j = css.find("{", i)
        if j < 0: return
        depth, k = 1, j + 1
        while depth and k < n:
            depth += {"{": 1, "}": -1}.get(css[k], 0); k += 1
        yield css[i:j].strip(), css[j + 1:k - 1]
        i = k

def convert(body):
    out = []
    for decl in body.split(";"):
        if ":" not in decl or not (HEX.search(decl) or RGB.search(decl)): continue
        prop, val = decl.split(":", 1)
        val = HEX.sub("var(--fx-accent)", val)
        val = RGB.sub(lambda m: f"color-mix(in srgb, var(--fx-accent) {round(float(m.group(1))*100)}%, transparent)", val)
        out.append(f"  {prop.strip()}: {val.strip()};")
    return out

def walk(css, indent=""):
    res = []
    for pre, body in blocks(css):
        if pre.startswith("@media") or pre.startswith("@supports"):
            inner = walk(body, indent + "  ")
            if inner: res.append(f"{indent}{pre} {{\n" + "\n".join(inner) + f"\n{indent}}}")
        elif "keyframes" in pre:
            # A later @keyframes of the same name replaces the earlier one,
            # so re-emit the whole animation with the colour swapped.
            if HEX.search(body) or RGB.search(body):
                res.append(f"{indent}{pre} {{{HEX.sub('var(--fx-accent)', body)}}}")
        elif pre.startswith("@"):
            continue
        else:
            decls = convert(body)
            if decls:
                sel = ",\n".join(indent + s.strip() for s in pre.split(","))
                res.append(f"{sel} {{\n" + "\n".join(indent + d for d in decls) + f"\n{indent}}}")
    return res

parts, count = [], 0
for src in SOURCES:
    css = strip_comments((ROOT / src).read_text(encoding="utf-8"))
    rules = walk(css)
    count += sum(r.count("var(--fx-accent)") for r in rules)
    parts.append(f"/* ---- from {src} ---- */\n" + "\n\n".join(rules))

header = ("/* GENERATED by scripts/build-accent-css.py — do not edit by hand.\n"
          "   Re-points every accent declaration in the vendor theme at\n"
          "   var(--fx-accent), defined in theme.css. */\n\n")
(ROOT / "src/styles/accent.css").write_text(header + "\n\n".join(parts) + "\n", encoding="utf-8")
print("declarations rewritten:", count)
